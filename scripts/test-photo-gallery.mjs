import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/lib/photo-gallery.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { galleryPhotos } = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputText).toString('base64'));
const photograph = id => ({ id, mime: 'image/jpeg', width: 1200, height: 1800 });
const video = { id: 'video', mime: 'video/mp4', thumbnailUrl: '/poster.jpg' };
const blank = { id: 'blank', title: '', content: null, assets: [] };
const mixed = { id: 'mixed', title: '', content: null, assets: [video, photograph('one'), photograph('two')] };
const authored = { id: 'authored', title: '原来的题目', content: '原来的文字', assets: [photograph('three')] };
const result = galleryPhotos([blank, { ...blank, assets: [video] }, mixed, authored]);
assert.deepEqual(result.map(item => item.asset.id), ['one', 'two', 'three'], 'Text records and video posters do not consume a photo slot; every actual photo keeps its order');
assert.equal(result[0].memory, mixed, 'The gallery preserves the original record');
assert.equal(result[0].memory.title, '', 'An absent title stays absent');
assert.equal(result[0].memory.content, null, 'An absent caption stays absent');
assert.equal(result[2].memory.content, authored.content, 'Authored content is unchanged');
assert.deepEqual(galleryPhotos([mixed, mixed, authored]).map(item => item.asset.id), ['one', 'two', 'three'], 'Repeated assets do not create repeated gallery entries');
assert.deepEqual(galleryPhotos([blank, mixed], 1).map(item => item.asset.id), ['one'], 'The limit applies after media filtering');
assert.deepEqual(galleryPhotos([mixed], 0), []);
assert.deepEqual(galleryPhotos([]), []);
console.log('PASS: photo-only gallery selection, mixed records, order, deduplication, limits and unchanged authored text.');
